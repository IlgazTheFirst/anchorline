// Bundles the anchorline CLI and MCP server into one ESM file that runs with
// plain `node`. The output is committed inside the Claude skill so the skill
// and the Claude Code plugin are self-contained; CI checks it is up to date.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const outfile = new URL('../skills/anchorline/scripts/anchorline.mjs', import.meta.url).pathname;

await build({
  entryPoints: [new URL('../src/cli/main.ts', import.meta.url).pathname],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  minify: true,
  legalComments: 'eof',
  charset: 'utf8',
  define: { __ANCHORLINE_VERSION__: JSON.stringify(pkg.version) },
  banner: {
    js: [
      '#!/usr/bin/env node',
      `// anchorline ${pkg.version}: plan around what can't move. MIT License. https://github.com/IlgazTheFirst/anchorline`,
      '// Generated by scripts/build-cli.mjs from src/; do not edit by hand.',
      "import { createRequire as __anchorlineCreateRequire } from 'node:module';",
      'const require = __anchorlineCreateRequire(import.meta.url);',
    ].join('\n'),
  },
  logLevel: 'warning',
});
console.log(`Built ${outfile}`);
